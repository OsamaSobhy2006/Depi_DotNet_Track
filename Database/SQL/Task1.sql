SELECT P.PNAME, COUNT(W.ESSN) AS [NUMBER OF EMPLOYEES] FROM PROJECT P LEFT JOIN WORKS_ON W ON P.PNUMBER = W.PNO GROUP BY P.PNAME;

SELECT D.DNAME, MAX(E.SALARY) AS [MAX SALARY], MIN(E.SALARY) AS [MIN SALARY], AVG(E.SALARY) AS [AVERAGE SALARY] FROM DEPARTMENT D JOIN EMPLOYEE E ON D.DNUMBER = E.DNO GROUP BY D.DNAME;

