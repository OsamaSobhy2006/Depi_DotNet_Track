SELECT E.FNAME + ' ' + E.LNAME AS [EMPLOYEE NAME], P.PNAME AS [PROJECT NAME] FROM EMPLOYEE E JOIN WORKS_ON W ON E.SSN = W.ESSN JOIN PROJECT P ON W.PNO = P.PNUMBER ORDER BY P.PNAME;

SELECT P.PNUMBER, D.DNAME, E.LNAME, E.ADDRESS, E.BDATE FROM PROJECT P JOIN DEPARTMENT D ON P.DNUM = D.DNUMBER JOIN EMPLOYEE E ON D.MGRSSN = E.SSN WHERE P.PLOCATION = 'Cairo';

SELECT E.* FROM EMPLOYEE E JOIN DEPARTMENT D ON E.SSN = D.MGRSSN;

SELECT E.FNAME + ' ' + E.LNAME AS [EMPLOYEE NAME], DEP.* FROM EMPLOYEE E LEFT JOIN DEPENDENT DEP ON E.SSN = DEP.ESSN;

