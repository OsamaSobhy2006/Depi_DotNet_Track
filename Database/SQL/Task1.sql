SELECT DEPENDENT.*, FNAME + ' ' + LNAME AS [EMPLOYEE NAME] FROM DEPENDENT JOIN EMPLOYEE ON ESSN = SSN;

SELECT PNUMBER, PNAME, PLOCATION FROM PROJECT WHERE PLOCATION IN ('Cairo', 'Alex');

SELECT * FROM PROJECT WHERE PNAME LIKE 'A%';

